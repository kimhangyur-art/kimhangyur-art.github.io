/**
 * Decompress gzip data using native Web API or fallback
 */
async function decompressGzip(data: Uint8Array): Promise<string> {
    try {
        // Try native DecompressionStream (modern browsers)
        if (typeof DecompressionStream !== 'undefined') {
            const stream = new DecompressionStream('gzip')
            const writer = stream.writable.getWriter()
            writer.write(new Uint8Array(data.buffer as ArrayBuffer, data.byteOffset, data.byteLength))
            writer.close()

            const reader = stream.readable.getReader()
            const chunks: Uint8Array[] = []

            while (true) {
                const { done, value } = await reader.read()
                if (done) break
                chunks.push(value)
            }

            const totalLength = chunks.reduce((acc, chunk) => acc + chunk.length, 0)
            const result = new Uint8Array(totalLength)
            let offset = 0
            for (const chunk of chunks) {
                result.set(chunk, offset)
                offset += chunk.length
            }

            return new TextDecoder('utf-8').decode(result)
        }
    } catch (e) {
        console.log('Native decompression failed, trying pako fallback:', e)
    }

    // Fallback to pako if available
    try {
        const pako = await import('pako')
        return pako.ungzip(data, { to: 'string' })
    } catch (e) {
        console.error('Gzip decompression failed:', e)
        throw new Error('Failed to decompress gzip data')
    }
}

export interface NAIMetadata {
    // Basic params
    prompt?: string
    negativePrompt?: string  // "uc" in NAI format

    // Generation settings
    model?: string  // Extracted from "Source" PNG tEXt chunk
    steps?: number
    cfgScale?: number  // "scale" in NAI
    cfgRescale?: number
    seed?: number
    sampler?: string
    scheduler?: string  // "noise_schedule" in NAI

    // SMEA
    smea?: boolean  // "sm" in NAI
    smeaDyn?: boolean  // "sm_dyn" in NAI
    variety?: boolean // Derived from "skip_cfg_above_sigma"
    qualityToggle?: boolean // "qualityToggle" - Add Quality Tags
    ucPreset?: number // "ucPreset" - Undesired Content Preset (0=Heavy, 1=Light, 2=Furry, 3=Human, 4=None)

    // Resolution
    width?: number
    height?: number

    // V4 specific
    v4_prompt?: {
        caption?: {
            base_caption?: string
            char_captions?: Array<{
                char_caption: string
                centers: Array<{ x: number, y: number }>
            }>
        }
    }
    v4_negative_prompt?: {
        caption?: {
            base_caption?: string
            char_captions?: Array<{
                char_caption: string
                centers: Array<{ x: number, y: number }>
            }>
        }
    }

    // Reference images (metadata only, not actual images)
    hasVibeTransfer?: boolean
    hasCharacterReference?: boolean

    // Vibe Transfer details (strength, info_extracted per image)
    vibeTransferInfo?: Array<{
        strength: number
        informationExtracted: number
    }>

    // Pre-encoded vibe data (for reuse without re-encoding)
    encodedVibes?: string[]

    // Character Reference details
    characterReferenceInfo?: Array<{
        strength: number
        informationExtracted: number
    }>

    // Source info
    source?: 'text_chunk' | 'stealth_alpha'

    // Raw data for debugging
    raw?: Record<string, unknown>

    // Original NAIS2 prompt sections (populated only when the image was
    // generated by NAIS2 and contains a nais2-params chunk with promptParts).
    promptParts?: {
        base: string
        additional: string
        detail: string
        negative?: string
        inpainting?: string
    }

    // ComfyUI (NAIS2 Comfy 그림의 Comment.comfy, 또는 ComfyUI 'prompt' 그래프에서)
    /** 체크포인트 파일 이름. 있으면 model 도 같은 값 */
    checkpoint?: string
    loras?: MetaLora[]
    /** 1 = 건너뛰지 않음, 2 = CLIP skip 2 */
    clipSkip?: number
    /** 고화질 단계 (없으면 null 또는 undefined) */
    hires?: HiresSettings | null
    /** 변형 모드에서 무엇을 바꾼 그림인지 */
    variant?: { label: string; values: Record<string, string> }
    /** '고화질로 다시 그리기'로 만든 그림이면 그때 값 */
    upscaledFrom?: { scale: number; denoise: number; method: string }
}

