/**
 * Extract metadata from alpha channel (stealth_pnginfo)
 * This method works even after images are uploaded to SNS
 * Ported from legacy Python stealth_png_reader.py
 */
async function extractStealthMetadata(imageData: ImageData): Promise<NAIMetadata | null> {
    try {
        const { data, width, height } = imageData
        const SIGNATURES = {
            alpha: {
                uncompressed: 'stealth_pnginfo',
                compressed: 'stealth_pngcomp'
            }
        }

        // Get pixel data - data is in RGBA order, row by row
        const getPixel = (x: number, y: number) => {
            const i = (y * width + x) * 4
            return {
                r: data[i],
                g: data[i + 1],
                b: data[i + 2],
                a: data[i + 3]
            }
        }

        const sigLen = SIGNATURES.alpha.uncompressed.length * 8 // bits
        let bufferA = ""
        let indexA = 0
        let sigConfirmed = false
        let confirmingSignature = true
        let readingParamLen = false
        let readingParam = false
        let readEnd = false
        let paramLen = 0
        let binaryData = ""
        let compressed = false

        // Column-major traversal - x first, then y (like legacy code)
        for (let x = 0; x < width && !readEnd; x++) {
            for (let y = 0; y < height && !readEnd; y++) {
                const pixel = getPixel(x, y)

                // Read LSB from alpha channel
                bufferA += (pixel.a & 1).toString()
                indexA++

                if (confirmingSignature) {
                    if (indexA === sigLen) {
                        // Convert binary string to text
                        const sig = binaryToString(bufferA)
                        if (sig === SIGNATURES.alpha.uncompressed) {
                            confirmingSignature = false
                            sigConfirmed = true
                            readingParamLen = true
                            compressed = false
                            bufferA = ""
                            indexA = 0
                        } else if (sig === SIGNATURES.alpha.compressed) {
                            confirmingSignature = false
                            sigConfirmed = true
                            readingParamLen = true
                            compressed = true
                            bufferA = ""
                            indexA = 0
                        } else {
                            readEnd = true
                            break
                        }
                    }
                } else if (readingParamLen) {
                    if (indexA === 32) {
                        paramLen = parseInt(bufferA, 2)
                        readingParamLen = false
                        readingParam = true
                        bufferA = ""
                        indexA = 0
                    }
                } else if (readingParam) {
                    if (indexA === paramLen) {
                        binaryData = bufferA
                        readEnd = true
                        break
                    }
                }
            }
        }

        if (!sigConfirmed || binaryData.length === 0) {
            return null
        }

        // Convert binary string to bytes
        const byteData = binaryToBytes(binaryData)

        // Decompress if needed
        let jsonString: string
        if (compressed) {
            jsonString = await decompressGzip(byteData)
        } else {
            jsonString = new TextDecoder('utf-8').decode(byteData)
        }

        // Parse JSON
        let jsonData = JSON.parse(jsonString)

        // Handle nested Comment field
        if (jsonData.Comment && typeof jsonData.Comment === 'string') {
            try {
                jsonData.Comment = JSON.parse(jsonData.Comment)
            } catch { /* ignore */ }
        }

        // Convert to our format - the main data is often in jsonData.Comment
        const sourceData = jsonData.Comment || jsonData
        const metadata = convertNAIFormat(sourceData)
        metadata.source = 'stealth_alpha'

        return metadata
    } catch (error) {
        console.log('Stealth metadata extraction failed:', error)
        return null
    }
}

/**
 * Convert binary string to text
 */
function binaryToString(binStr: string): string {
    const bytes: number[] = []
    for (let i = 0; i < binStr.length; i += 8) {
        const byte = binStr.slice(i, i + 8)
        if (byte.length === 8) {
            bytes.push(parseInt(byte, 2))
        }
    }
    return new TextDecoder('utf-8').decode(new Uint8Array(bytes))
}

/**
 * Convert binary string to Uint8Array
 */
function binaryToBytes(binStr: string): Uint8Array {
    const bytes: number[] = []
    for (let i = 0; i < binStr.length; i += 8) {
        const byte = binStr.slice(i, i + 8)
        if (byte.length === 8) {
            bytes.push(parseInt(byte, 2))
        }
    }
    return new Uint8Array(bytes)
}

/**
 * Detect image MIME type from bytes
 */
function detectImageType(bytes: Uint8Array): string {
    // PNG: 89 50 4E 47 0D 0A 1A 0A
    if (bytes[0] === 0x89 && bytes[1] === 0x50 && bytes[2] === 0x4E && bytes[3] === 0x47) {
        return 'image/png'
    }
    // WebP: RIFF....WEBP
    if (bytes[0] === 0x52 && bytes[1] === 0x49 && bytes[2] === 0x46 && bytes[3] === 0x46 &&
        bytes[8] === 0x57 && bytes[9] === 0x45 && bytes[10] === 0x42 && bytes[11] === 0x50) {
        return 'image/webp'
    }
    // JPEG: FF D8 FF
    if (bytes[0] === 0xFF && bytes[1] === 0xD8 && bytes[2] === 0xFF) {
        return 'image/jpeg'
    }
    // Default to PNG
    return 'image/png'
}

/**
 * Load image and get ImageData using Canvas API
 * Supports PNG, WebP, JPEG
 */
async function getImageData(imageBytes: Uint8Array): Promise<ImageData | null> {
    return new Promise((resolve) => {
        const mimeType = detectImageType(imageBytes)
        const blob = new Blob([new Uint8Array(imageBytes.buffer as ArrayBuffer, imageBytes.byteOffset, imageBytes.byteLength)], { type: mimeType })
        const url = URL.createObjectURL(blob)
        const img = new Image()

        img.onload = () => {
            let canvas: HTMLCanvasElement | null = document.createElement('canvas')
            canvas.width = img.width
            canvas.height = img.height
            const ctx = canvas.getContext('2d')

            if (!ctx) {
                URL.revokeObjectURL(url)
                img.src = '' // Clear image reference
                canvas.width = 0 // Release canvas memory
                canvas.height = 0
                resolve(null)
                return
            }

            ctx.drawImage(img, 0, 0)
            const imageData = ctx.getImageData(0, 0, img.width, img.height)
            
            // CRITICAL: Release resources to prevent OOM
            URL.revokeObjectURL(url)
            img.src = ''
            canvas.width = 0
            canvas.height = 0
            canvas = null
            
            resolve(imageData)
        }

        img.onerror = () => {
            URL.revokeObjectURL(url)
            img.src = ''
            resolve(null)
        }

        img.src = url
    })
}

/**
 * Parse image metadata (PNG tEXt chunks or stealth alpha channel)
 * Supports PNG and WebP formats
 */
export async function parseNAIMetadata(imageData: ArrayBuffer | Uint8Array): Promise<NAIMetadata | null> {
    try {
        const bytes = imageData instanceof ArrayBuffer ? new Uint8Array(imageData) : imageData
        const imageType = detectImageType(bytes)

        let metadata: NAIMetadata | null = null

        if (imageType === 'image/png') {
            metadata = await extractTextChunkMetadata(bytes)
        } else if (imageType === 'image/webp') {
            metadata = extractWebpExifMetadata(bytes)
        }

        // If no metadata found yet, try stealth alpha channel (works for PNG/WebP)
        if (!metadata) {
            const imgData = await getImageData(bytes)
            if (imgData) {
                metadata = await extractStealthMetadata(imgData)
            }
        }

        return metadata
    } catch (error) {
        console.error('Failed to parse metadata:', error)
        return null
    }
}

/**
 * Extract NAI metadata from a WebP file's EXIF chunk.
 *
 * NAI v4+ stores a single JSON object in the EXIF chunk with the shape:
 *   { "Comment": "<nested JSON string>", "Description": "...", "Software": "NovelAI",
 *     "Source": "NovelAI Diffusion V4.5 XXXXX", "Title": "...", "Generation time": "..." }
 *
 * We locate the outer JSON by brace-balance (rather than parsing full EXIF/TIFF),
 * then feed the inner Comment JSON to convertNAIFormat.
 */
function extractWebpExifMetadata(bytes: Uint8Array): NAIMetadata | null {
    // RIFF header: "RIFF" <size:u32le> "WEBP"
    if (bytes.length < 12) return null
    if (bytes[0] !== 0x52 || bytes[1] !== 0x49 || bytes[2] !== 0x46 || bytes[3] !== 0x46) return null
    if (bytes[8] !== 0x57 || bytes[9] !== 0x45 || bytes[10] !== 0x42 || bytes[11] !== 0x50) return null

    const decoder = new TextDecoder('utf-8')
    let off = 12
    while (off + 8 <= bytes.length) {
        const fourcc = String.fromCharCode(bytes[off], bytes[off + 1], bytes[off + 2], bytes[off + 3])
        const size = bytes[off + 4] | (bytes[off + 5] << 8) | (bytes[off + 6] << 16) | (bytes[off + 7] << 24)
        const dataStart = off + 8
        const dataEnd = dataStart + size
        if (dataEnd > bytes.length) break

        if (fourcc === 'EXIF') {
            const exifText = decoder.decode(bytes.subarray(dataStart, dataEnd))
            // Locate the outer JSON object by finding the first '{' and balancing braces.
            const jsonStart = exifText.indexOf('{"Comment"')
            if (jsonStart >= 0) {
                let depth = 0
                let inString = false
                let escape = false
                let jsonEnd = -1
                for (let i = jsonStart; i < exifText.length; i++) {
                    const ch = exifText[i]
                    if (escape) { escape = false; continue }
                    if (ch === '\\') { escape = true; continue }
                    if (ch === '"') { inString = !inString; continue }
                    if (inString) continue
                    if (ch === '{') depth++
                    else if (ch === '}') {
                        depth--
                        if (depth === 0) { jsonEnd = i + 1; break }
                    }
                }
                if (jsonEnd > jsonStart) {
                    try {
                        const outer = JSON.parse(exifText.slice(jsonStart, jsonEnd))
                        if (typeof outer.Comment === 'string') {
                            const inner = JSON.parse(outer.Comment)
                            const metadata = convertNAIFormat(inner)
                            metadata.source = 'text_chunk'
                            if (typeof outer.Source === 'string') metadata.model = outer.Source
                            const modelKey = detectModelKey(metadata.model)
                            const inferred = inferNAIPresets(metadata.prompt, metadata.negativePrompt, modelKey)
                            if (metadata.qualityToggle === undefined && inferred.qualityToggle !== undefined) {
                                metadata.qualityToggle = inferred.qualityToggle
                            }
                            if (metadata.ucPreset === undefined && inferred.ucPreset !== undefined) {
                                metadata.ucPreset = inferred.ucPreset
                            }
                            return metadata
                        }
                    } catch (e) {
                        console.error('[WebP EXIF] JSON parse failed:', e)
                    }
                }
            }
        }

        // Chunks are padded to even byte boundary.
        off = dataEnd + (size & 1)
    }
    return null
}

/**
 * Extract metadata from PNG tEXt chunks
 */
async function extractTextChunkMetadata(bytes: Uint8Array): Promise<NAIMetadata | null> {
    let offset = 8
    let metadata: NAIMetadata | null = null
    let modelSource: string | null = null
    let comfyPrompt: string | null = null

    while (offset < bytes.length) {
        // Read chunk length (4 bytes, big-endian)
        const length = (bytes[offset] << 24) | (bytes[offset + 1] << 16) |
            (bytes[offset + 2] << 8) | bytes[offset + 3]
        offset += 4

        // Read chunk type (4 bytes)
        const type = String.fromCharCode(bytes[offset], bytes[offset + 1],
            bytes[offset + 2], bytes[offset + 3])
        offset += 4

        if (type === 'tEXt' || type === 'iTXt') {
            // Read chunk data
            const chunkData = bytes.slice(offset, offset + length)
            const textData = new TextDecoder('utf-8').decode(chunkData)

            // tEXt format: keyword\0value
            const nullIndex = textData.indexOf('\0')
            if (nullIndex !== -1) {
                const keyword = textData.slice(0, nullIndex)
                let value = textData.slice(nullIndex + 1)

                // iTXt has additional fields before the actual text
                if (type === 'iTXt') {
                    const parts = value.split('\0')
                    value = parts[parts.length - 1] || value
                }

                if (keyword === 'Comment' || keyword === 'parameters') {
                    try {
                        const parsed = JSON.parse(value)
                        metadata = convertNAIFormat(parsed)
                        metadata.source = 'text_chunk'
                    } catch {
                        metadata = parseA1111Format(value)
                        if (metadata) metadata.source = 'text_chunk'
                    }
                } else if (keyword === 'Source') {
                    // Store model source temporarily, will be added after metadata is created
                    modelSource = value
                } else if (keyword === 'prompt') {
                    // ComfyUI API 작업 그래프 (Comment 가 없을 때만 쓴다)
                    comfyPrompt = value
                }
            }
        }

        // Skip chunk data and CRC
        offset += length + 4

        // Stop at IEND
        if (type === 'IEND') break
    }

    // Add model source if found (우리 그림이면 Source 도 체크포인트 이름이다)
    if (metadata && modelSource) {
        metadata.model = modelSource
    }

    // If this image was produced by NAIS2, trust our own nais2-params chunk
    // (qualityToggle / ucPreset / promptParts as we sent them) over any heuristic.
    // Comment 가 없는 그림도 nais2-params 만으로 읽는다. ComfyUI 그래프에서 읽은 그림에는 섞지 않는다
    // (그래프의 글은 품질 태그·UC가 이미 붙은 최종 글이라서).
    const nais2 = readNais2Params(bytes)

    // Comment·parameters 가 없으면 ComfyUI 작업 그래프에서 찾는다
    if (!metadata && comfyPrompt) {
        try {
            metadata = parseComfyPromptGraph(JSON.parse(comfyPrompt))
        } catch (e) {
            console.warn('[metadata] ComfyUI prompt graph parse failed:', e)
        }
    }
    if (!metadata && nais2) {
        metadata = { source: 'text_chunk', raw: { nais2 } }
    }
    if (metadata && nais2 && metadata.raw?.comfyuiPrompt === undefined) {
        if (typeof nais2.qualityToggle === 'boolean') metadata.qualityToggle = nais2.qualityToggle
        if (typeof nais2.ucPreset === 'number') metadata.ucPreset = nais2.ucPreset
        if (nais2.promptParts && typeof nais2.promptParts === 'object') {
            const pp = nais2.promptParts
            metadata.promptParts = {
                base: pp.base ?? '',
                additional: pp.additional ?? '',
                detail: pp.detail ?? '',
                negative: pp.negative,
                inpainting: pp.inpainting,
            }
            // Comment 없이 nais2-params 만 있으면 칸들을 합쳐 프롬프트로 보여 준다
            if (metadata.prompt === undefined) {
                const joined = [pp.base, pp.additional, pp.detail]
                    .map((s) => (s ?? '').trim().replace(/^,+|,+$/g, '').trim())
                    .filter(Boolean)
                    .join(', ')
                if (joined) metadata.prompt = joined
            }
            if (metadata.negativePrompt === undefined && pp.negative) metadata.negativePrompt = pp.negative
        }
    }

    // Heuristically recover qualityToggle / ucPreset from prompt/uc text only
    // when the nais2-params chunk did not supply them (images from NAI web,
    // third-party tools, etc.). NAI v4/v4.5 never embeds these flags in the
    // Comment JSON.
    if (metadata) {
        const modelKey = detectModelKey(metadata.model)
        const inferred = inferNAIPresets(metadata.prompt, metadata.negativePrompt, modelKey)
        if (metadata.qualityToggle === undefined && inferred.qualityToggle !== undefined) {
            metadata.qualityToggle = inferred.qualityToggle
        }
        if (metadata.ucPreset === undefined && inferred.ucPreset !== undefined) {
            metadata.ucPreset = inferred.ucPreset
        }
    }

    return metadata
}

